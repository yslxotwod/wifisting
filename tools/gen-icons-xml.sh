#!/usr/bin/env bash
# Regenerate wifisting.gresource.xml.
#
# glib-compile-resources has no glob, so every file is listed. Adding an
# icon means re-running this; tools/check-paths.sh reports an icon on disk
# that the resource does not carry, which is how that gets noticed.
set -euo pipefail
ROOT="$(cd -P "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out="$ROOT/native/resources/wifisting.gresource.xml"

{
    printf '<?xml version="1.0" encoding="UTF-8"?>\n'
    printf '<!-- Generated by tools/gen-icons-xml.sh. Do not edit by hand. -->\n'
    printf '<gresources>\n'
    printf '  <gresource prefix="/com/wifisting/native">\n'
    printf '    <file>style.css</file>\n'
    ( cd "$ROOT/native/resources" && find icons/symbolic -name '*.svg' | LC_ALL=C sort ) \
        | sed 's|^|    <file>|; s|$|</file>|'
    printf '  </gresource>\n'
    printf '</gresources>\n'
} > "$out"
printf 'wrote %s (%s entries)\n' "$out" "$(grep -c '<file>' "$out")"
